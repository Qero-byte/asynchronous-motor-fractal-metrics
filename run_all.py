#!/usr/bin/env python
"""features -> audit -> statistics -> figures -> summary.

    python run_all.py                     # everything
    python run_all.py --skip-features     # reuse results/tables/window_features.csv
    python run_all.py --jobs 4            # parallel feature extraction
    python run_all.py --skip-surrogates   # skip the expensive nulls
"""
from __future__ import annotations

import argparse
import glob
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

from fractal_metrics import (CHANNELS, RESULTS_DIR, TABLES_DIR,
                             extract_features, quantization_table, zoh_demo)
import figures as FG
import group_statistics as GS

FEATURES = TABLES_DIR / "window_features.csv"
RESULTS_MD = RESULTS_DIR / "RESULTS.md"


# --------------------------------------------------------------------------
# feature table loading / shard merging
# --------------------------------------------------------------------------

def merge_shards(out: Path = FEATURES) -> pd.DataFrame | None:
    """Merge results/tables/_shard_*.csv into the full feature table."""
    shards = sorted(glob.glob(str(TABLES_DIR / "_shard_*.csv")))
    if not shards:
        return None
    df = pd.concat([pd.read_csv(s) for s in shards], ignore_index=True)
    front = [c for c in ["stem", "record", "motor", "condition",
                         "file_phase_loss", "load_nm", "regime", "win_index",
                         "i0", "i1", "t0", "t1"] if c in df.columns]
    df = df[front + [c for c in df.columns if c not in front]]
    df = df.sort_values(["record", "win_index"]).reset_index(drop=True)
    df.to_csv(out, index=False)
    print(f"merged {len(shards)} shards -> {out}  ({df.shape[0]} x {df.shape[1]})")
    return df


def load_features() -> pd.DataFrame:
    """Load the feature table, preferring shards that are newer than it."""
    shards = sorted(glob.glob(str(TABLES_DIR / "_shard_*.csv")))
    if shards:
        newest = max(Path(s).stat().st_mtime for s in shards)
        if not FEATURES.exists() or FEATURES.stat().st_mtime < newest:
            merged = merge_shards()
            if merged is not None:
                return merged
    if FEATURES.exists():
        return pd.read_csv(FEATURES)
    merged = merge_shards()
    if merged is not None:
        return merged
    raise SystemExit(f"{FEATURES} not found and no shards to merge; "
                     f"run without --skip-features")

# RESULTS.md

def _md(df: pd.DataFrame, **kw) -> str:
    """Markdown table, falling back to a fenced block without tabulate."""
    try:
        return df.to_markdown(index=False, **kw)
    except Exception:                                      # noqa: BLE001
        fence = chr(96) * 3
        return fence + chr(10) + df.to_string(index=False) + chr(10) + fence


def write_summary(tables: dict, audit_tbl: pd.DataFrame, path: Path) -> None:
    """Write results/RESULTS.md from the tables computed in this run."""
    cmp_df = tables.get("comparisons", pd.DataFrame())
    cls = tables.get("classification", pd.DataFrame())
    icc = tables.get("record_variance")
    fam = tables.get("record_variance_family")
    sur = tables.get("surrogates")
    esur = tables.get("entropy_surrogates")
    rlev = tables.get("record_level")
    wrec = tables.get("within_record")

    lines = ["# Results summary (auto-generated by run_all.py)", ""]
    lines.append("Windows analysed: "
                 + (str(int(cmp_df["n_a"].iloc[0])) if len(cmp_df) else "0")
                 + " per group in the first comparison.")
    lines.append("")
    lines.append("## Value resolution (median over records)")
    lines.append("")
    med = audit_tbl.groupby("channel").agg(
        n_unique=("n_unique", "median"), step=("step", "median"),
        step_to_std=("step_to_std", "median")).reindex(list(CHANNELS))
    lines.append(_md(med.reset_index(), floatfmt=".3g"))
    lines.append("")
    lines.append("## Group comparisons (top 8 features by |AUC-0.5|)")
    lines.append("")
    for key, g in cmp_df.groupby("comparison", sort=False):
        lines.append(f"### {g['label'].iloc[0]}")
        lines.append("")
        cols = ["feature", "n_a", "n_b", "median_a", "median_b",
                "auc", "q_bh", "cliffs_d"]
        lines.append(_md(g.head(8)[cols], floatfmt=".4g"))
        lines.append("")
    if cls is not None and not cls.empty:
        lines.append("## Classification (RandomForest)")
        lines.append("")
        lines.append(_md(cls, floatfmt=".4g"))
        lines.append("")
    if icc is not None and not icc.empty:
        lines.append("## Record-identity confound")
        lines.append("")
        lines.append(f"Share of features with eta^2(record) >= 0.8: "
                     f"**{float((icc['eta2_record'] >= 0.8).mean()):.1%}**; "
                     f">= 0.5: **{float((icc['eta2_record'] >= 0.5).mean()):.1%}**. ")
        lines.append("")
        lines.append(_md(icc.head(15), floatfmt=".4g"))
        lines.append("")
        if fam is not None and not fam.empty:
            lines.append("### By feature family (does preprocessing reduce the "
                         "session confound?)")
            lines.append("")
            lines.append(_md(fam.reset_index(), floatfmt=".4g"))
            lines.append("")
    if sur is not None and not sur.empty:
        lines.append("## Surrogate validation (is the multifractality dynamical?)")
        lines.append("")
        cols = [c for c in ["channel", "kind", "group", "stem", "surrogate",
                            "n", "dalpha_mean", "dalpha_std", "h2_mean"]
                if c in sur.columns]
        lines.append(_md(sur[cols].sort_values(["channel", "group", "surrogate"]),
                         floatfmt=".4g"))
        lines.append("")
    if esur is not None and not esur.empty:
        lines.append("## Entropy surrogate validation")
        lines.append("")
        lines.append(_md(esur, floatfmt=".4g"))
        lines.append("")
    if rlev is not None and not rlev.empty:
        lines.append("## Hierarchical inference (window -> recording)")
        lines.append("")
        cols = [c for c in ["comparison", "unit", "n_records_a", "n_records_b",
                            "n_shared", "family", "n_features", "n_p05", "min_p",
                            "auc_record_median"] if c in rlev.columns]
        lines.append(_md(rlev[cols], floatfmt=".4g"))
        lines.append("")
    if wrec is not None and not wrec.empty:
        lines.append("### Within-recording cyclic-shift test")
        lines.append("")
        cols = [c for c in ["stem", "family", "n_windows", "n_open",
                            "min_p_shift", "n_p05"] if c in wrec.columns]
        lines.append(_md(wrec[cols], floatfmt=".4g"))
        lines.append("")
    path.write_text(chr(10).join(lines), encoding="utf-8")
    print(f"WROTE {path}")

# main

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Reproduce every table and figure of the paper")
    ap.add_argument("--jobs", type=int, default=None, help="worker processes")
    ap.add_argument("--only", nargs="*", default=None,
                    help="restrict feature extraction to these record stems")
    ap.add_argument("--skip-features", action="store_true")
    ap.add_argument("--skip-audit", action="store_true")
    ap.add_argument("--skip-classify", action="store_true")
    ap.add_argument("--skip-surrogates", action="store_true")
    ap.add_argument("--skip-figures", action="store_true")
    ap.add_argument("--multi-surrogates", action="store_true",
                    help="also run the pooled multi-window robustness check "
                         "(three windows per group, four nulls; ~90 min)")
    args = ap.parse_args(argv)

    t0 = time.time()

    #1 features
    if args.skip_features:
        df = load_features()
        print(f"loaded {FEATURES}  ({df.shape[0]} x {df.shape[1]})")
    else:
        df = extract_features(only=args.only, jobs=args.jobs)
        if df.empty:
            print("no windows extracted", file=sys.stderr)
            return 1
        df.to_csv(FEATURES, index=False)
        print(f"WROTE {FEATURES}  ({df.shape[0]} x {df.shape[1]})")

    #2 audit
    quant = None
    demo = None
    print()
    print("[audit]")
    if not args.skip_audit:
        quant = quantization_table()
        quant.to_csv(TABLES_DIR / "quantization.csv", index=False)
        print(f"  quantization.csv ({quant.shape[0]} rows)")
        try:
            demo = zoh_demo()
            payload = {"zoh": demo["zoh"], "stem": demo["stem"],
                       "channel": demo["channel"]}
            payload.update({f"{k}_{i}": v for k, d in demo.items()
                            if isinstance(d, dict) for i, v in d.items()})
            np.savez_compressed(TABLES_DIR / "zoh_demo.npz", **payload)
            print(f"  zoh_demo.npz (detected hold = {demo['zoh']} samples)")
        except Exception as exc:                           # noqa: BLE001
            print(f"  !! zoh_demo: {exc!r}", file=sys.stderr)
    else:
        p = TABLES_DIR / "quantization.csv"
        if p.exists():
            quant = pd.read_csv(p)

    #3 statistics
    print()
    print("[statistics]")
    tables = GS.write_tables(df, surrogates=not args.skip_surrogates,
                             do_classify=not args.skip_classify,
                             multi=args.multi_surrogates)
    rlev = tables.get("record_level")
    if rlev is not None and not rlev.empty:
        print("  comparisons with a family significant at the record level: "
              f"{int((rlev['min_p'] <= 0.05).sum())} of {len(rlev)}")

    #4 figures
    if not args.skip_figures:
        print()
        print("[figures]")
        FG.draw_all(df, tables.get("comparisons"),
                    tables.get("classification"), tables.get("record_variance"),
                    quant, demo)

    #5 summary
    if quant is not None:
        write_summary(tables, quant, RESULTS_MD)
    print()
    print(f"done in {time.time() - t0:.0f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
